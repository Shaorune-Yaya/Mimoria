// ======================================================
// Helpers
// ======================================================

function normalizeLocale(
  locale
) {
  const normalized =
    String(
      locale || ""
    )
      .trim()
      .toLowerCase();


  if (
    normalized.startsWith(
      "zh"
    )
  ) {
    return "zh-CN";
  }


  return "en";
}


function fallbackLabel(
  conceptId,
  locale = "en"
) {
  const normalizedLocale =
    normalizeLocale(
      locale
    );


  const localizedLabel =
    FALLBACK_LABELS[
      normalizedLocale
    ]?.[
      conceptId
    ];


  if (
    localizedLabel
  ) {
    return localizedLabel;
  }


  const raw =
    String(
      conceptId || ""
    )
      .replace(
        /^entityType\./u,
        ""
      );


  if (
    !raw
  ) {
    return normalizedLocale ===
      "zh-CN"
      ? "实体类型"
      : "Entity Type";
  }


  return raw
    .replace(
      /([a-z])([A-Z])/gu,
      "$1 $2"
    )
    .replace(
      /^./u,
      (character) =>
        character.toUpperCase()
    );
}


function getEntityTypePresentation(
  conceptId,
  locale = "en"
) {
  const entry =
    PRESENTATION[
      conceptId
    ];


  const normalizedLocale =
    normalizeLocale(
      locale
    );


  if (
    !entry
  ) {
    return {
      conceptId,

      icon:
        "📄",

      label:
        fallbackLabel(
          conceptId,
          normalizedLocale
        ),
    };
  }


  return {
    conceptId,

    icon:
      entry.icon ||
      "📄",

    label:
      entry
        .labels
        ?.[
          normalizedLocale
        ] ||
      entry
        .labels
        ?.en ||
      fallbackLabel(
        conceptId,
        normalizedLocale
      ),
  };
}


